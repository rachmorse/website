    <p>In Iquitos, Peru—a city in the middle of the Amazon rainforest—our team introduced a new cervical cancer prevention program. 
        Although this program increased the number of women receiving treatment at local clinics for HPV—the primary cause of 
        cervical cancer—many who require hospital-based treatment still slip through the cracks and do not receive the care they 
        need. To understand why, we spoke with both the patients and the healthcare professionals overseeing their treatment. </p>
    <p>We found that some patients lacked sufficient information about HPV and felt shut out by a complicated referral system. 
        Even when they managed to reach the hospital, scheduling issues and confusing instructions caused some to drop out 
        of treatment. Similarly, healthcare professionals identified communication gaps that left patients without vital information 
        on HPV and its treatment and noted the need for a unified registry to track patient care. Based on these findings, 
        we recommend stronger integration of registries between clinics and hospitals, better training for healthcare professionals, 
        and the introduction of patient navigators who can offer clear information and support. </p>
