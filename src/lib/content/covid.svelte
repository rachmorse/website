    <p>Almost half of all dementia cases can be prevented by addressing modifiable risk factors such as social 
        isolation and physical inactivity. However, during the COVID-19 pandemic, many older adults experienced 
        disruptions to their usual routines and were not able to continue their activities.</p>
    <p>In this study, we set out to understand how older adults with memory concerns experienced these challenges. 
        We found that while some relied on technology or community support to maintain an active lifestyle, 
        others faced barriers like limited digital access, increased social isolation, poorer mental health, 
        and reduced physical activity. We suggest that dementia prevention programs prioritize building 
        digitally inclusive communities and ensure that cognitively vulnerable older adults receive the 
        support they need—both now and in any future pandemic.</p>

